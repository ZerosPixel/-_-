function prepareBunkerEventPlan(bunker, catastrophe) {
  const allowed = BUNKER_EVENTS.filter(event => !event.catastropheIds || event.catastropheIds.includes(catastrophe.id));
  const candidates = shuffle(allowed);
  const selected = [];
  let capacityAlreadySelected = false;
  const usedProblemTypes = new Set();
  for (const event of candidates) {
    if (selected.length >= 5) break;
    const isCapacityEvent = event.kind === 'capacity' || event.capacityEvent === true;
    if (isCapacityEvent && capacityAlreadySelected) continue;
    if (event.kind === 'problem' && usedProblemTypes.has(event.problemType)) continue;
    selected.push({ ...clonePlain(event), stage: selected.length, discovered: false, applied: false, resolved: false });
    if (isCapacityEvent) capacityAlreadySelected = true;
    if (event.kind === 'problem') usedProblemTypes.add(event.problemType);
  }
  return selected;
}

function applyBunkerEffect(g, event, effect, effectKey) {
  const bs = g.bunkerState;
  if (!bs || !effect || !effectKey || bs.appliedEffects.includes(effectKey)) return false;
  if (Number.isFinite(effect.capacity)) {
    bs.capacity.current = clamp(bs.capacity.current + effect.capacity, 0, MAX_PLAYERS);
    g.capacity = bs.capacity.current;
  }
  if (effect.resource && Object.prototype.hasOwnProperty.call(bs.resources, effect.resource)) {
    bs.resources[effect.resource] = Math.max(0, Number(bs.resources[effect.resource] || 0) + Number(effect.delta || 0));
  }
  if (effect.infrastructure) {
    Object.entries(effect.infrastructure).forEach(([key, delta]) => {
      if (Object.prototype.hasOwnProperty.call(bs.infrastructure, key)) bs.infrastructure[key] = clamp(Number(bs.infrastructure[key] || 0) + Number(delta || 0), 0, 100);
    });
  }
  bs.appliedEffects.push(effectKey);
  return true;
}

function revealBunkerEvent(stageIndex) {
  const g = state.game;
  const bs = g?.bunkerState;
  const planned = g?.bunkerEventPlan?.[stageIndex];
  if (!bs || !planned || planned.discovered) return false;
  planned.discovered = true;
  const event = clonePlain(planned);
  event.discovered = true;
  event.roundDiscovered = g.round || 1;
  bs.events.push(event);
  bs.discoveries.push({ id: event.id, title: event.title, description: event.description, round: g.round || 1 });
  if (event.kind === 'problem') {
    if (!bs.activeProblems.some(problem => problem.id === event.id)) {
      bs.activeProblems.push({ id: event.id, title: event.title, category: event.category, problemType: event.problemType, description: event.description, severity: 1 });
    }
  }
  if (event.effect && Object.keys(event.effect).length) {
    event.applied = applyBunkerEffect(g, event, event.effect, `${event.id}:discover`);
  }
  g.log.push(`Обнаружено в бункере: ${event.title}.`);
  return true;
}

function catastropheFactModifier(catastrophe, stageIndex, factText = '') {
  const tags = Array.isArray(catastrophe?.scenarioTags) ? catastrophe.scenarioTags : [];
  const tag = tags.length ? tags[stageIndex % tags.length] : '';
  const text = String(factText || '').toLowerCase();
  const positive = /(сохранил|сохранилась|сохранились|можно использовать|может дать|работоспособен|исправен|безопасный маршрут|редкие тёплые окна|помогает|дополнительн\w+ ресурс)/i.test(text);
  const direction = positive ? -1 : 1;
  const effect = { foodNeed: 0, waterNeed: 0, heatNeed: 0, techNeed: 0, medicalNeed: 0, environmentPenalty: 0, systemsPenalty: 0 };
  if (['cold','ash','climate','dry'].includes(tag)) {
    effect.heatNeed = tag === 'cold' || tag === 'climate' ? .035 * direction : 0;
    effect.foodNeed = tag === 'dry' ? .025 * direction : .015 * direction;
  } else if (['water'].includes(tag)) {
    effect.waterNeed = .04 * direction;
    effect.environmentPenalty = .8 * direction;
  } else if (['sanitation','health','filters'].includes(tag)) {
    effect.medicalNeed = .035 * direction;
    effect.environmentPenalty = .8 * direction;
  } else if (['power','systems','energy'].includes(tag)) {
    effect.techNeed = .035 * direction;
    effect.systemsPenalty = .8 * direction;
  } else if (['food'].includes(tag)) {
    effect.foodNeed = .04 * direction;
  } else if (['structure'].includes(tag)) {
    effect.techNeed = .025 * direction;
    effect.environmentPenalty = .8 * direction;
  } else if (['dust'].includes(tag)) {
    effect.environmentPenalty = .8 * direction;
    effect.waterNeed = .015 * direction;
  }
  return effect;
}

function applyCatastropheFactEffect(g, fact) {
  if (!g || !fact?.id || !fact.modifiers) return false;
  g.appliedCatastropheEffects ||= [];
  if (g.appliedCatastropheEffects.includes(fact.id)) return false;
  g.catastropheModifiers ||= { foodNeed: 0, waterNeed: 0, heatNeed: 0, techNeed: 0, medicalNeed: 0, environmentPenalty: 0, systemsPenalty: 0 };
  Object.entries(fact.modifiers).forEach(([key, delta]) => {
    if (Object.prototype.hasOwnProperty.call(g.catastropheModifiers, key)) {
      g.catastropheModifiers[key] += Number(delta || 0);
    }
  });
  g.appliedCatastropheEffects.push(fact.id);
  fact.effectApplied = true;
  return true;
}

function revealCatastropheFact(stageIndex) {
  const g = state.game;
  const facts = g?.catastrophe?.facts || [];
  if (!g || stageIndex < 0 || stageIndex >= facts.length) return false;
  if ((g.catastropheReveals || []).some(item => item.stage === stageIndex)) return false;
  const source = facts[stageIndex];
  const text = typeof source === 'string' ? source : String(source?.text || '');
  const id = typeof source === 'object' && source?.id ? source.id : `${g.catastrophe.id || 'scenario'}-fact-${stageIndex + 1}`;
  const modifiers = typeof source === 'object' && source?.modifiers
    ? clonePlain(source.modifiers)
    : catastropheFactModifier(g.catastrophe, stageIndex, text);
  const historyText = Array.isArray(g.catastrophe.history) && stageIndex < g.catastrophe.history.length
    ? String(g.catastrophe.history[stageIndex] || '')
    : '';
  const fact = { id, stage: stageIndex, text, history: historyText, modifiers, round: g.round || 1, effectApplied: false };
  if (typeof source === 'object') fact.title = source.title || '';
  applyCatastropheFactEffect(g, fact);
  g.catastropheReveals.push(fact);
  g.log.push(`Открыты новые сведения: ${g.catastrophe.title}.`);
  return true;
}

function discoverWorldStage(stageIndex) {
  const g = state.game;
  if (!g || !state.isHost || stageIndex < 0) return false;
  g.worldStagesDiscovered ||= [];
  if (g.worldStagesDiscovered.includes(stageIndex)) return false;
  g.worldStagesDiscovered.push(stageIndex);
  const catChanged = revealCatastropheFact(stageIndex);
  const bunkerChanged = revealBunkerEvent(stageIndex);
  return catChanged || bunkerChanged;
}

function revealFinalWorldKnowledge() {
  const g = state.game;
  const count = Math.max(g?.catastrophe?.facts?.length || 0, g?.bunkerEventPlan?.length || 0);
  for (let stage = 0; stage < count; stage++) discoverWorldStage(stage);
}

