  g.currentPhase = 'discussion';
  g.currentSpeechIndex = 0;
  g.voteRound = (Number(g.voteRound) || 0) + 1;
  g.votes = {};
  g.voteLocks = {};
  g.skipChoices = {};
  g.votingLocked = false;
  g.needsRevote = false;
  eligibleVoters().forEach(p => { p.vote = null; });
