function startTimer(seconds) {
  if (!state.isHost || !state.game) return;
  const g = state.game;
  const duration = Math.max(0, Math.floor(Number(seconds) || 0));
  g.timeLeft = duration;
  g.timerDeadline = Date.now() + duration * 1000;
  g.timerRunning = duration > 0;
  g.timerExpiredHandled = false;
  syncAndRender();
  refreshTimerDisplay();
}

function stopTimer() {
  if (!state.isHost || !state.game) return;
  state.game.timerRunning = false;
  state.game.timerDeadline = null;
  state.game.timerExpiredHandled = false;
  syncAndRender();
}

function refreshTimerDisplay() {
  const g = state.game;
  if (!g || !g.timerRunning || !Number.isFinite(Number(g.timerDeadline))) return;
  const left = Math.max(0, Math.ceil((Number(g.timerDeadline) - Date.now()) / 1000));
  g.timeLeft = left;
  document.querySelectorAll('.timer').forEach(element => {
    const display = formatTime(left);
    if (element.textContent !== display) element.textContent = display;
  });
  if (left === 0 && state.isHost && !g.timerExpiredHandled) {
    g.timerExpiredHandled = true;
    g.timerRunning = false;
    g.timerDeadline = null;
    autoAdvanceTimerPhase();
  }
}

function autoAdvanceTimerPhase() {
  const g = state.game;
  if (g.currentPhase === 'turns') finishTurn();
  else if (g.currentPhase === 'discussion' || g.currentPhase === 'vote') finishVote(true);
  else if (g.currentPhase === 'defense') finishDefense();
  else if (g.currentPhase === 'farewell') finishFarewell();
  else if (g.currentPhase === 'speeches') beginDiscussion();
}

function clonePlain(value) {
  if (typeof structuredClone === 'function') {
    try { return structuredClone(value); } catch (e) { console.warn('structuredClone fallback', e); }
  }
  return JSON.parse(JSON.stringify(value));
}

function sanitizeForPeer(g, playerId) {
  const clone = clonePlain(g);
  const revealEverything = g.status === 'finished' || g.currentPhase === 'final';
  clone.players = clone.players.map(p => {
    const q = { ...p };
    delete q.clientId;
    delete q.peerId;
    q.cards = {};
    for (const [type] of CARD_TYPES) {
      const card = p.cards?.[type] || {};
      const revealed = revealEverything || (Array.isArray(p.revealed) && p.revealed.includes(type));
      q.cards[type] = p.id === playerId
        ? { type, value: card.value ?? null, mods: { ...(card.mods || {}) } }
        : revealed
          ? { type, value: card.value ?? null, revealed: true, mods: {} }
          : { type, value: null, revealed: false, mods: {} };
    }
    return q;
  });
  if (clone.catastrophe) {
    delete clone.catastrophe.history;
    delete clone.catastrophe.facts;
    delete clone.catastrophe.story;
  }
  // Only discoveries are shared. The unannounced event queue remains on the host.
  delete clone.bunkerEventPlan;
  if (clone.bunkerState) {
    clone.bunkerState.events = (clone.bunkerState.events || []).map(e => ({
      id: e.id, title: e.title, description: e.description, category: e.category,
      stage: e.stage, discovered: !!e.discovered, resolved: !!e.resolved,
      resolutionText: e.resolutionText || '', kind: e.kind,
      applied: !!e.applied, problemType: e.problemType || null,
      repairable: false, costMaterials: 0
    }));
    delete clone.bunkerState.eventPlan;
  }
  return clone;
}

function broadcast() {
  if (!state.isHost) return;
  sendStateToAll();
}

function sendStateToConnection(conn) {
  if (!state.isHost || !state.game || !conn?.open || !conn.metadata?.playerId) return false;
  try {
    const playerId = conn.metadata.playerId;
    conn.send({ type: 'state', game: sanitizeForPeer(state.game, playerId) });
    conn.metadata.lastSentSeq = state.game.stateSeq || 0;
    return true;
  } catch (error) {
    console.error('Не удалось подготовить состояние игроку', error);
    return false;
  }
}

function sendStateToAll() {
  if (!state.isHost || !state.game) return;
  for (const conn of state.connections.values()) sendStateToConnection(conn);
}

function syncAndRender() {
  if (state.isHost && state.game) state.game.stateSeq = (Number(state.game.stateSeq) || 0) + 1;
  render();
  if (state.isHost) sendStateToAll();
}

function attachHostConnection(conn) {
  // Do not register a participant merely because the transport opened.
  conn.on('open', () => {
    try { conn.send({ type: 'hello', roomCode: state.roomCode, protocolVersion: 2 }); }
    catch (error) { console.warn('hello send failed', error); }
  });
  conn.on('data', msg => handleHostMessage(conn, msg));
  conn.on('close', () => {
    state.connections.delete(conn.peer);
    const playerId = conn.metadata?.playerId;
    const p = playerId ? playerById(playerId) : null;
    if (p && p.peerId === conn.peer) {
      // Льготный период: мобильный браузер часто рвёт канал на секунды и тут же
      // переподключается — не показываем «нет связи», пока игрок не пропал надолго.
      const lostPeerId = conn.peer;
      setTimeout(() => {
        if (!state.isHost || !state.game || p.peerId !== lostPeerId) return;
        p.connected = false;
        p.ready = false;
        p.peerId = null;
        state.game?.log?.push(`${p.name} потерял соединение.`);
        syncAndRender();
      }, 15000);
      return;
    }
    if (state.game && state.isHost) syncAndRender();
  });
  conn.on('error', e => console.warn('PeerJS connection error', e));
}


function sendToHost(message) {
  const conn = state.pendingHost;
  if (!conn?.open || !message || typeof message !== 'object') {
    toast('Нет связи с комнатой. Переподключитесь.');
    return false;
  }
  try {
    conn.send({ ...message, sessionId: state.joinSessionId || undefined });
    return true;
  } catch (error) {
    console.warn('Не удалось отправить действие хосту', error);
    toast('Не удалось отправить действие. Попробуйте ещё раз.');
    return false;
  }
}

function handleHostMessage(conn, msg) {
  if (!msg || typeof msg !== 'object' || !state.isHost || !state.game) return;
  if (msg.action === 'joinLobby') {
    handleHostJoinLobby(conn, msg);
    return;
  }
  if (msg.action === 'stateAck') {
    if (conn.metadata?.sessionId && msg.sessionId !== conn.metadata.sessionId) return;
    const pid = conn.metadata?.playerId;
    const player = pid ? playerById(pid) : null;
    if (!player || player.peerId !== conn.peer) return;
    const ackSeq = Number(msg.sequence);
    const latestSeq = Number(state.game.stateSeq) || 0;
    if (Number.isFinite(ackSeq) && ackSeq === latestSeq && ackSeq === Number(conn.metadata.lastSentSeq)) {
      const wasReady = player.ready;
      player.ready = true;
      player.connected = true;
      if (!wasReady) syncAndRender();
    } else {
      sendStateToConnection(conn);
    }
    return;
  }

  if (conn.metadata?.sessionId && msg.sessionId !== conn.metadata.sessionId) return;
  const playerId = conn.metadata?.playerId;
  const player = playerId ? playerById(playerId) : null;
  if (!player || player.peerId !== conn.peer || !player.connected) return;
  if (msg.action === 'requestState') {
    sendStateToConnection(conn);
    return;
  }
  if (msg.action === 'leaveRoom') {
    disconnectPlayerConnection(conn);
    return;
  }
  if (msg.action === 'reveal') {
    const ok = revealCard(player.id, msg.type);
    if (msg.requestId) {
      try { conn.send({ type: 'actionResult', requestId: String(msg.requestId), ok: !!ok, message: ok ? '' : 'Раскрытие не принято. Проверьте текущий ход.' }); } catch {}
    }
    return;
  }
  if (msg.action === 'finishTurn') {
    const current = currentTurnPlayer();
    if (current?.id === player.id) finishTurn();
    return;
  }
  if (msg.action === 'vote') {
    castVote(player.id, String(msg.targetId || ''));
    return;
  }
  if (msg.action === 'skipChoice') {
    setSkipChoice(player.id, !!msg.enabled);
    return;
  }
  if (msg.action === 'lockVote') {
    lockVote(player.id);
    return;
  }
  // Host phase controls are local-only. A regular client cannot start timers,
  // skip phases, finish a vote, kick players, or directly edit shared state.
}

function disconnectPlayerConnection(conn) {
  const playerId = conn?.metadata?.playerId;
  const p = playerId ? playerById(playerId) : null;
  if (p && p.peerId === conn.peer) {
    p.connected = false;
    p.ready = false;
    p.peerId = null;
  }
  state.connections.delete(conn.peer);
  try { conn.close(); } catch {}
  if (state.game) syncAndRender();
}

function clearJoinTimeout() {
  if (state.joinTimeoutHandle) clearTimeout(state.joinTimeoutHandle);
  state.joinTimeoutHandle = null;
}

function closeClientPeer() {
  clearJoinTimeout();
  try { state.pendingHost?.close(); } catch {}
  try { state.peer?.destroy(); } catch {}
  state.pendingHost = null;
  state.peer = null;
  state.myId = null;
}

function scheduleHostPeerReconnect() {
  if (!state.isHost || !state.peer || state.peer.destroyed) return;
  if (state.hostReconnectTimer) clearTimeout(state.hostReconnectTimer);
  state.hostReconnectTimer = setTimeout(() => {
    state.hostReconnectTimer = null;
    if (!state.isHost || !state.peer || state.peer.destroyed || !state.peer.disconnected) return;
    try { state.peer.reconnect(); } catch (error) {
      console.warn('Host signaling reconnect failed', error);
      scheduleHostPeerReconnect();
    }
  }, 2500);
}
function createHost(name) {
  if (state.joinBusy) return;
  if (typeof Peer !== 'function') { state.joinError = 'Не удалось загрузить сетевой модуль. Проверьте доступ к CDN и обновите страницу.'; toast(state.joinError); render(); return; }
  state.joinBusy = true;
  state.connectionLost = false;
  state.isHost = true;
  state.roomCode = makeRoomCode();
  state.hostId = `bunker-${state.roomCode}`;
  rememberName(name);
  const peer = new Peer(state.hostId, { debug: 1 });
  state.peer = peer;
  setBadge('создаём комнату…');
  peer.on('open', () => {
    if (state.isHost && state.game) {
      setBadge(`комната ${state.roomCode} · сигнализация активна`, true);
      sendStateToAll();
      return;
    }
    state.joinBusy = false;
    const playerNames = [state.myName];
    state.game = createGame({ playerCount: 1 }, playerNames, 0);
    state.game.capacity = 0;
    state.game.roomTitle = makeRoomTitle(state.game.catastrophe, state.game.bunker);
    state.game.players.forEach(p => p.ready = true);
    state.game.players[0].clientId = state.clientId;
    state.game.players[0].peerId = peer.id;
    state.myPlayerId = state.game.players[0].id;
    state.mode = 'lobby';
    const url = new URL(location.href);
    url.search = `?room=${encodeURIComponent(state.roomCode)}`;
    history.replaceState(null, '', url);
    setBadge(`комната ${state.roomCode}`, true);
    render();
    toast('Комната создана. Отправьте ссылку друзьям.');
  });
  peer.on('connection', attachHostConnection);
  peer.on('error', err => {
    console.error(err);
    state.joinBusy = false;
    setBadge('ошибка подключения');
    toast(err?.type === 'unavailable-id' ? 'Код комнаты уже занят. Попробуйте создать комнату ещё раз.' : 'Не удалось создать комнату. Проверьте соединение.');
    render();
  });
  peer.on('disconnected', () => {
    setBadge('сигнализация отключена · переподключаемся');
    scheduleHostPeerReconnect();
  });
}

const MAX_AUTO_REJOIN = 10;
// Тихое автоподключение: пока хост ещё не открыл комнату или связь мигнула,
// участник видит «подключаемся…», а не ошибку «нет связи / комната не найдена».
function scheduleAutoRejoin() {
  if (state.isHost || state.mode === 'kicked' || !state.roomCode || !state.myName) return false;
  if (state.autoRejoinCount >= MAX_AUTO_REJOIN) return false;
  state.autoRejoinCount++;
  const delay = Math.min(1500 * state.autoRejoinCount, 6000);
  setBadge(`подключаемся к комнате ${state.roomCode}…`);
  clearTimeout(state.autoRejoinTimer);
  state.autoRejoinTimer = setTimeout(() => {
    state.autoRejoinTimer = null;
    if (state.isHost || state.mode === 'kicked') return;
    state.joinBusy = false;
    joinRoom(state.roomCode, state.myName);
  }, delay);
  return true;
}

function joinRoom(roomCode, name) {
  if (!roomCode || state.joinBusy) return;
  if (typeof Peer !== 'function') {
    state.joinBusy = false;
    state.joinError = 'Не удалось загрузить сетевой модуль. Обновите страницу или проверьте доступ к CDN.';
    state.mode = 'start';
    setBadge('сетевой модуль недоступен');
    render();
    return;
  }
  clearJoinTimeout();
  const attempt = ++state.joinAttemptId;
  state.joinSessionId = `session-${attempt}-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
  state.joinBusy = true;
  state.joinError = '';
  state.connectionLost = false;
  state.signalingRetryCount = 0;
  state.isHost = false;
  state.myPlayerId = null;
  state.lastStateSeq = 0;
  state.hostId = `bunker-${String(roomCode).trim().toUpperCase()}`;
  state.roomCode = String(roomCode).trim().toUpperCase();
  rememberName(name);
  state.mode = 'joining';
  setBadge(`подключение к ${state.roomCode}…`);
  render();
  closeClientPeer();

  const peer = new Peer(undefined, { debug: 1 });
  state.peer = peer;
  const attemptIsCurrent = () => attempt === state.joinAttemptId && state.peer === peer;
  const failAttempt = message => {
    if (!attemptIsCurrent()) return;
    clearJoinTimeout();
    if (scheduleAutoRejoin()) {
      try { state.pendingHost?.close(); } catch {}
      try { peer.destroy(); } catch {}
      state.pendingHost = null;
      state.peer = null;
      state.joinBusy = true;
      state.joinError = '';
      state.connectionLost = false;
      render();
      return;
    }
    state.joinBusy = false;
    state.joinError = message || 'Не удалось получить состояние комнаты. Попробуйте подключиться ещё раз.';
    state.connectionLost = true;
    try { state.pendingHost?.close(); } catch {}
    try { peer.destroy(); } catch {}
    state.pendingHost = null;
    state.peer = null;
    setBadge('ошибка связи');
    render();
  };
  state.joinTimeoutHandle = setTimeout(() => {
    if (attemptIsCurrent() && state.joinBusy) failAttempt('Не удалось получить состояние комнаты. Попробуйте подключиться ещё раз.');
  }, 30000);

  peer.on('open', myId => {
    if (!attemptIsCurrent()) return;
    state.myId = myId;
    const conn = peer.connect(state.hostId, { reliable: true, serialization: 'json' });
    state.pendingHost = conn;
    conn.on('data', msg => { if (attemptIsCurrent()) handleClientMessage(msg, attempt); });
    conn.on('open', () => {
      if (!attemptIsCurrent()) return;
      setBadge(`комната ${state.roomCode} · получение состояния`, false);
      // The host sends hello; registration happens exactly once in handleClientMessage.
      render();
    });
    conn.on('close', () => {
      if (!attemptIsCurrent() || state.mode === 'kicked') return;
      clearJoinTimeout();
      state.pendingHost = null;
      if (scheduleAutoRejoin()) {
        state.joinBusy = true;
        state.connectionLost = false;
        render();
        return;
      }
      state.connectionLost = true;
      state.joinBusy = false;
      setBadge('нет связи с комнатой');
      toast('Связь с хостом потеряна. Можно переподключиться.');
      render();
    });
    conn.on('error', err => {
      if (!attemptIsCurrent()) return;
      console.warn('PeerJS data connection error', err);
      if (state.joinBusy) failAttempt('Канал связи оборвался до получения состояния комнаты. Проверьте сеть и попробуйте снова.');
    });
  });
  peer.on('error', err => {
    if (!attemptIsCurrent()) return;
    console.error('PeerJS error', err);
    failAttempt(err?.type === 'peer-unavailable' ? 'Комната не найдена. Проверьте код или ссылку.' : 'Не удалось установить соединение. Попробуйте ещё раз.');
  });
  peer.on('disconnected', () => {
    if (!attemptIsCurrent()) return;
    setBadge('сигнальная связь восстанавливается');
    if (state.signalingRetryCount < 2) {
      state.signalingRetryCount++;
      try { peer.reconnect(); } catch (error) { console.warn('Peer signaling reconnect failed', error); }
    }
  });
  peer.on('close', () => {
    if (!attemptIsCurrent()) return;
    state.connectionLost = true;
  });
}

function handleClientMessage(msg, attempt = state.joinAttemptId) {
  if (!msg || typeof msg !== 'object' || attempt !== state.joinAttemptId) return;
  if (msg.type === 'hello') {
    if (String(msg.roomCode || '').toUpperCase() !== String(state.roomCode || '').toUpperCase()) return;
    setBadge(`комната ${state.roomCode} · регистрация`, false);
    const conn = state.pendingHost;
    if (conn?.open && !conn.metadata?.registrationSent) {
      // A local flag on the DataConnection prevents duplicate registration messages.
      conn.metadata = { ...(conn.metadata || {}), registrationSent: true };
      conn.send({ action: 'joinLobby', name: state.myName, peerId: state.myId, clientId: state.clientId, sessionId: state.joinSessionId });
    }
    return;
  }
  if (msg.type === 'assigned') {
    if (!msg.playerId || (msg.sessionId && msg.sessionId !== state.joinSessionId)) return;
    state.myPlayerId = String(msg.playerId);
    setBadge(`комната ${state.roomCode} · синхронизация`, false);
    // Assignment is not readiness: explicitly request a current snapshot in case
    // the initial snapshot was lost while the mobile browser was resuming.
    try { state.pendingHost?.send({ action: 'requestState', sessionId: state.joinSessionId }); }
    catch (error) { console.warn('Initial state request failed', error); }
    return;
  }
  if (msg.type === 'error') {
    clearJoinTimeout();
    state.joinBusy = false;
    state.joinError = String(msg.message || 'Комната отклонила подключение.');
    setBadge('ошибка комнаты');
    toast(msg.message || 'Комната отклонила подключение.');
    render();
    return;
  }
  if (msg.type === 'kicked') {
    state.mode = 'kicked';
    state.connectionLost = false;
    state.joinBusy = false;
    state.game = null;
    closeClientPeer();
    setBadge('удалён из комнаты');
    render();
    toast('Хост удалил вас из комнаты.');
    return;
  }
  if (msg.type === 'actionResult') {
    const pending = state.pendingRevealRequests.get(String(msg.requestId || ''));
    if (!pending) return;
    clearTimeout(pending.timer);
    state.pendingRevealRequests.delete(String(msg.requestId));
    if (!msg.ok) {
      if (pending.button?.isConnected) {
        pending.button.disabled = false;
        pending.button.textContent = 'Раскрыть';
      }
      toast(String(msg.message || 'Действие не подтверждено.')); 
    }
    return;
  }
  if (msg.type === 'state') {
    const game = msg.game;
    if (!game || !Array.isArray(game.players) || !game.currentPhase || !game.status) return;
    if (!state.myPlayerId || !game.players.some(p => p.id === state.myPlayerId)) return;
    state.autoRejoinCount = 0;
    const sequence = Number(game.stateSeq) || 0;
    if (sequence && sequence <= state.lastStateSeq) {
      try { state.pendingHost?.send({ action: 'stateAck', sequence: state.lastStateSeq, sessionId: state.joinSessionId }); } catch {}
      return;
    }
    // Apply first, then acknowledge. Transport/open alone is not considered ready.
    state.game = game;
    state.lastStateSeq = sequence;
    state.mode = 'game';
    state.joinBusy = false;
    state.joinError = '';
    state.connectionLost = false;
    state.signalingRetryCount = 0;
    clearJoinTimeout();
    setBadge(game.status === 'lobby' ? 'лобби синхронизировано' : 'в игре', true);
    render();
    try { state.pendingHost?.send({ action: 'stateAck', sequence, sessionId: state.joinSessionId }); }
    catch (error) { console.warn('State acknowledgement failed', error); }
  }
}

function handleHostJoinLobby(conn, msg) {
  if (!state.isHost || !state.game || msg?.action !== 'joinLobby') return false;
  const clientId = String(msg.clientId || '').trim().slice(0, 128);
  const name = String(msg.name || '').trim().slice(0, 28);
  if (!clientId || !name) {
    try { conn.send({ type: 'error', message: 'Не удалось определить участника. Повторите подключение.' }); } catch {}
    try { conn.close(); } catch {}
    return true;
  }
  let target = state.game.players.find(p => p.clientId === clientId);

  if (target?.eliminated) {
    try { conn.send({ type: 'kicked', message: 'Вы уже выбыли из этой партии.' }); } catch {}
    setTimeout(() => { try { conn.close(); } catch {} }, 250);
    return true;
  }

  // A returning player keeps the same slot, cards, avatar identity and vote/state.
  if (target) {
    if (target.peerId && target.peerId !== conn.peer) {
      const old = state.connections.get(target.peerId);
      state.connections.delete(target.peerId);
      try { old?.close(); } catch {}
    }
  } else {
    if (state.game.status !== 'lobby') {
      try { conn.send({ type: 'error', message: 'Игра уже началась. Вернуться можно только с ранее зарегистрированного устройства.' }); } catch {}
      try { conn.close(); } catch {}
      return true;
    }
    if (state.game.players.length >= MAX_PLAYERS) {
      try { conn.send({ type: 'error', message: 'Комната заполнена: максимум 15 участников.' }); } catch {}
      try { conn.close(); } catch {}
      return true;
    }
    target = makePlayers([name], null, 1)[0];
    target.slot = Math.max(0, ...state.game.players.map(p => Number(p.slot) || 0)) + 1;
    state.game.players.push(target);
    assignUniqueItemCards(state.game.players);
  }

  target.name = name;
  target.occupied = true;
  target.clientId = clientId;
  target.peerId = conn.peer;
  target.connected = true;
  target.ready = false; // Ready means a current state snapshot was applied and acknowledged.
  conn.metadata = { ...(conn.metadata || {}), playerId: target.id, clientId, sessionId: String(msg.sessionId || `legacy-${conn.peer}-${Date.now().toString(36)}`) };
  state.connections.set(conn.peer, conn);
  try { conn.send({ type: 'assigned', playerId: target.id, roomCode: state.roomCode, sessionId: conn.metadata.sessionId }); }
  catch (error) { console.warn('assignment failed', error); return true; }
  state.game.log.push(`${target.name} вошёл в комнату.`);
  syncAndRender();
  return true;
}

function kickPlayer(playerId) {
  if (!state.isHost || !state.game) return;
  const g = state.game;
  if (g.status === 'finished') return toast('Партия уже завершена.');
  const p = playerById(playerId);
  if (!p || p.hostPlayer || p.eliminated) return toast('Этот игрок недоступен для удаления.');

  // Send a terminal notice before closing; immediate close can win a race on mobile.
  const peerId = p.peerId;
  const conn = peerId ? state.connections.get(peerId) : null;
  if (peerId) state.connections.delete(peerId);
  p.peerId = null; // stale close handlers cannot mutate this player's next session
  if (conn?.open) {
    try { conn.send({ type: 'kicked', message: 'Хост удалил вас из комнаты.' }); } catch {}
    setTimeout(() => { try { conn.close(); } catch {} }, 250);
  } else {
    try { conn?.close(); } catch {}
  }

  if (g.status === 'lobby') {
    g.players = g.players.filter(item => item.id !== p.id);
    g.log.push(`Хост удалил ${p.name} из комнаты.`);
  } else {
    const previousPhase = g.currentPhase;
    const orderBeforeRemoval = orderedActive();
    const removedIndex = orderBeforeRemoval.findIndex(item => item.id === p.id);
    const oldTurnIndex = Number(g.currentTurnIndex) || 0;
    const oldSpeechIndex = Number(g.currentSpeechIndex) || 0;
    p.eliminated = true;
    p.connected = false;
    p.ready = false;
    p.bunkered = false;
    p.vote = null;
    delete g.votes[p.id];
    delete g.voteLocks[p.id];
    delete g.skipChoices[p.id];

    // A vote for a removed target is invalid. Unlock only those voters so they can reselect.
    const stillActiveIds = new Set(activePlayers().map(player => player.id));
    Object.keys(g.votes || {}).forEach(voterId => {
      if (!stillActiveIds.has(g.votes[voterId])) {
        delete g.votes[voterId];
        g.voteLocks[voterId] = false;
        const voter = playerById(voterId);
        if (voter) voter.vote = null;
      }
    });
    g.defenseQueue = (g.defenseQueue || []).filter(id => id !== p.id);
    g.defenseCandidates = (g.defenseCandidates || []).filter(id => id !== p.id);
    g.defendedThisRound = (g.defendedThisRound || []).filter(id => id !== p.id);
    g.log.push(`Хост удалил ${p.name} из партии.`);

    if (activePlayers().length <= Number(g.capacity || 0)) {
      finishGame();
      return;
    }
    if (previousPhase === 'turns' && removedIndex >= 0) {
      if (removedIndex < oldTurnIndex) g.currentTurnIndex = Math.max(0, oldTurnIndex - 1);
      else if (removedIndex === oldTurnIndex && oldTurnIndex >= orderedActive().length) {
        beginDiscussion();
        return;
      }
    } else if (previousPhase === 'speeches' && removedIndex >= 0) {
      if (removedIndex < oldSpeechIndex) {
        g.currentSpeechIndex = Math.max(0, oldSpeechIndex - 1);
      } else if (removedIndex === oldSpeechIndex) {
        g.currentSpeechIndex = Math.max(-1, oldSpeechIndex - 1);
        if (orderedActive().length === 0) { beginVote(); return; }
        nextSpeech();
        return;
      }
      if (g.currentSpeechIndex >= orderedActive().length) {
        beginVote();
        return;
      }
    } else if (previousPhase === 'defense') {
      if (!g.defenseQueue.length) {
        startRevote();
        return;
      }
    } else if (previousPhase === 'discussion' || previousPhase === 'vote') {
      // The live phase is "discussion"; "vote" is a legacy phase name.
      const remainingVoters = eligibleVoters();
      if (!g.votingLocked && remainingVoters.length && remainingVoters.every(voter => !!g.voteLocks?.[voter.id])) {
        finishVote(false);
        return;
      }
    }
  }
  syncAndRender();
  toast('Игрок удалён.');
}

