  return ({ lobby:'Лобби', turns:'Ходы и раскрытие', discussion:'Общее обсуждение', speeches:'Речи', vote:'Голосование', defense:'Оправдание', farewell:'Прощальная речь', final:'Финал' })[g.currentPhase] || g.currentPhase;
